import { randomInt } from "node:crypto";
import { normalizeDatabaseRemote, SERVER_DATABASE_USERNAME_RANDOM_LENGTH, serverDatabaseFullName } from "@blockforge/contracts";

/**
 * SQL for the statements the control plane runs against MySQL/MariaDB hosts.
 *
 * `CREATE DATABASE`, `CREATE USER`, `GRANT`, `ALTER USER` and `DROP …` take identifiers and account
 * names, and `IDENTIFIED BY` takes a string literal: none of them accept `?` parameters. Every value that
 * reaches these statements is therefore (1) checked against a strict allowlist regex right here, at the
 * point of use, (2) backtick-quoted (identifiers, account parts) or single-quoted (passwords), and (3)
 * never user free text: database names are `s<shortId>_` + `[a-z0-9_]`, usernames and passwords are
 * generated by the control plane, and host patterns are normalised to `[a-z0-9.%:/-]`. Anything else
 * throws {@link UnsafeSqlValueError} before a statement is built.
 */

export class UnsafeSqlValueError extends Error {
  constructor(what: string) {
    super(`refusing unsafe ${what}`);
    this.name = "UnsafeSqlValueError";
  }
}

/** Full database names: `s` + 8 hex + `_` + 1–48 of `[a-z0-9_]` (≤ 58 < 64). */
export const DATABASE_NAME_RE = /^s[0-9a-f]{8}_[a-z0-9_]{1,48}$/;
/** Generated usernames: `u` + 8 hex + `_` + 10 of `[a-z0-9]` (20 ≤ 32). */
export const USERNAME_RE = /^u[0-9a-f]{8}_[a-z0-9]{10}$/;
/** Normalised host patterns (contracts `normalizeDatabaseRemote`). */
export const REMOTE_RE = /^[a-z0-9.%:/-]{1,60}$/;
/** Generated passwords: no quote, backslash or other character that is special in a MySQL string literal. */
export const PASSWORD_RE = /^[A-Za-z0-9._~-]{24,64}$/;
const SHORT_ID_RE = /^[0-9a-f]{8}$/;

/**
 * Privileges granted on the server's own database (`db`.*): Pterodactyl's list — everything a database
 * owner needs, but no GRANT OPTION, no global privileges and nothing on any other database.
 */
export const DATABASE_PRIVILEGES = [
  "SELECT",
  "INSERT",
  "UPDATE",
  "DELETE",
  "CREATE",
  "DROP",
  "ALTER",
  "REFERENCES",
  "INDEX",
  "LOCK TABLES",
  "CREATE ROUTINE",
  "ALTER ROUTINE",
  "EXECUTE",
  "CREATE TEMPORARY TABLES",
  "CREATE VIEW",
  "SHOW VIEW",
  "EVENT",
  "TRIGGER",
] as const;

function checked(value: string, re: RegExp, what: string): string {
  // The regexes exclude backticks, quotes, backslashes, whitespace and NUL; checked anyway before quoting.
  if (typeof value !== "string" || !re.test(value) || /[`'"\\\0\s]/.test(value)) throw new UnsafeSqlValueError(what);
  return value;
}

export const quoteDatabase = (name: string): string => `\`${checked(name, DATABASE_NAME_RE, "database name")}\``;
export const quoteAccount = (username: string, remote: string): string =>
  `\`${checked(username, USERNAME_RE, "username")}\`@\`${checked(remote, REMOTE_RE, "host pattern")}\``;
const quotePassword = (password: string): string => `'${checked(password, PASSWORD_RE, "password")}'`;

export const createDatabaseSql = (db: string): string => `CREATE DATABASE ${quoteDatabase(db)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`;
export const dropDatabaseSql = (db: string): string => `DROP DATABASE IF EXISTS ${quoteDatabase(db)}`;
export const createUserSql = (username: string, remote: string, password: string): string =>
  `CREATE USER ${quoteAccount(username, remote)} IDENTIFIED BY ${quotePassword(password)}`;
export const alterUserPasswordSql = (username: string, remote: string, password: string): string =>
  `ALTER USER ${quoteAccount(username, remote)} IDENTIFIED BY ${quotePassword(password)}`;
export const dropUserSql = (username: string, remote: string): string => `DROP USER IF EXISTS ${quoteAccount(username, remote)}`;
/**
 * In database-level GRANTs MySQL and MariaDB treat `_` and `%` in the database name as wildcards, so a grant
 * on `s0123abcd_a_b`.* would also cover `s0123abcd_aXb` — including the right to CREATE such databases.
 * `escapeWildcards` (every host except MySQL with `partial_revokes = ON`, which reads grant names
 * literally and would then not match the real database) escapes them as `\_`.
 */
export const grantSql = (db: string, username: string, remote: string, escapeWildcards: boolean): string => {
  const name = quoteDatabase(db);
  return `GRANT ${DATABASE_PRIVILEGES.join(", ")} ON ${escapeWildcards ? name.replaceAll("_", "\\_") : name}.* TO ${quoteAccount(username, remote)}`;
};
/** MySQL 8.0.16+ only (empty on MariaDB): `ON` makes grant database names literal. */
export const PARTIAL_REVOKES_SQL = "SHOW GLOBAL VARIABLES LIKE 'partial_revokes'";

const LOWER_ALNUM = "abcdefghijklmnopqrstuvwxyz0123456789";
const PASSWORD_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_.~";
export const GENERATED_PASSWORD_LENGTH = 32;

const randomFrom = (alphabet: string, length: number): string => {
  let out = "";
  for (let i = 0; i < length; i++) out += alphabet[randomInt(alphabet.length)];
  return out;
};

/** Full database name for a server (validated, so a bad short id or name never yields a statement). */
export function databaseNameFor(serverShortId: string, name: string): string {
  return checked(serverDatabaseFullName(checked(serverShortId, SHORT_ID_RE, "server id"), name), DATABASE_NAME_RE, "database name");
}

/** `u<shortId>_<10 random [a-z0-9]>` (Pterodactyl `u<serverId>_<random>`). */
export function generateUsername(serverShortId: string): string {
  return checked(`u${checked(serverShortId, SHORT_ID_RE, "server id")}_${randomFrom(LOWER_ALNUM, SERVER_DATABASE_USERNAME_RANDOM_LENGTH)}`, USERNAME_RE, "username");
}

/**
 * 32 characters (~190 bits) from `[A-Za-z0-9-_.~]`, with at least one upper, lower, digit and symbol so
 * that typical password-policy plugins (`validate_password` MEDIUM) accept it. The symbols are URL-unreserved
 * and need no escaping in SQL string literals or JDBC URLs.
 */
export function generatePassword(): string {
  for (;;) {
    const p = randomFrom(PASSWORD_ALPHABET, GENERATED_PASSWORD_LENGTH);
    if (/[A-Z]/.test(p) && /[a-z]/.test(p) && /\d/.test(p) && /[-_.~]/.test(p)) return p;
  }
}

/** Normalised, validated host pattern for SQL (throws on anything the contracts would refuse). */
export function remoteFor(input: string): string {
  const v = normalizeDatabaseRemote(input);
  if (v === null) throw new UnsafeSqlValueError("host pattern");
  return checked(v, REMOTE_RE, "host pattern");
}
