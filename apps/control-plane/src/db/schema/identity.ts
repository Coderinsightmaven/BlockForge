import { ALL_PERMISSIONS, ScopeType } from "@blockforge/contracts";
import { sql } from "drizzle-orm";
import { bigint, boolean, check, index, integer, jsonb, pgTable, primaryKey, text, unique, uuid } from "drizzle-orm/pg-core";
import { citext, enumCheck, tsz } from "./_helpers.js";

export const USER_STATUSES = ["active", "disabled"] as const;

export const users = pgTable(
  "users",
  {
    id: uuid("id").primaryKey(),
    email: citext("email").notNull().unique("users_email_unique"),
    displayName: text("display_name").notNull(),
    passwordHash: text("password_hash").notNull(),
    status: text("status").notNull().default("active"),
    mfaEnabled: boolean("mfa_enabled").notNull().default(false),
    /** TOTP secret encrypted with the master key (see secrets/crypto.ts, AAD bound to the user id). */
    mfaTotpSecretEnc: text("mfa_totp_secret_enc"),
    /** Secret generated by `/auth/mfa/enroll`, promoted on confirm. */
    mfaPendingSecretEnc: text("mfa_pending_secret_enc"),
    /** Last accepted TOTP time step (replay protection). */
    mfaLastTimeStep: bigint("mfa_last_time_step", { mode: "number" }),
    failedLoginCount: integer("failed_login_count").notNull().default(0),
    lockedUntil: tsz("locked_until"),
    lastLoginAt: tsz("last_login_at"),
    passwordChangedAt: tsz("password_changed_at"),
    createdAt: tsz("created_at").notNull().defaultNow(),
    updatedAt: tsz("updated_at").notNull().defaultNow(),
    version: integer("version").notNull().default(1),
  },
  (t) => [enumCheck("users_status_check", t.status, USER_STATUSES)],
);

export const sessions = pgTable(
  "sessions",
  {
    id: uuid("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    /** sha256(hex) of the opaque cookie token. */
    tokenHash: text("token_hash").notNull().unique("sessions_token_hash_unique"),
    /** sha256(hex) of the session-bound CSRF token. */
    csrfTokenHash: text("csrf_token_hash").notNull(),
    createdAt: tsz("created_at").notNull(),
    lastSeenAt: tsz("last_seen_at").notNull(),
    /** Absolute expiry (created + 7 d); idle expiry is last_seen_at + 12 h. */
    expiresAt: tsz("expires_at").notNull(),
    ip: text("ip"),
    userAgent: text("user_agent"),
    mfaVerified: boolean("mfa_verified").notNull().default(false),
    mfaFailedAttempts: integer("mfa_failed_attempts").notNull().default(0),
  },
  (t) => [index("sessions_user_idx").on(t.userId), index("sessions_expires_idx").on(t.expiresAt)],
);

export const roles = pgTable("roles", {
  id: uuid("id").primaryKey(),
  key: text("key").notNull().unique("roles_key_unique"),
  name: text("name").notNull(),
  description: text("description").notNull().default(""),
  builtin: boolean("builtin").notNull().default(false),
  createdAt: tsz("created_at").notNull().defaultNow(),
  updatedAt: tsz("updated_at").notNull().defaultNow(),
});

export const rolePermissions = pgTable(
  "role_permissions",
  {
    roleId: uuid("role_id")
      .notNull()
      .references(() => roles.id, { onDelete: "cascade" }),
    permission: text("permission").notNull(),
  },
  (t) => [
    primaryKey({ name: "role_permissions_pk", columns: [t.roleId, t.permission] }),
    enumCheck("role_permissions_permission_check", t.permission, ALL_PERMISSIONS),
  ],
);

export const roleBindings = pgTable(
  "role_bindings",
  {
    id: uuid("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    roleId: uuid("role_id")
      .notNull()
      .references(() => roles.id, { onDelete: "restrict" }),
    scopeType: text("scope_type").notNull(),
    scopeId: uuid("scope_id"),
    createdAt: tsz("created_at").notNull().defaultNow(),
    createdBy: uuid("created_by").references(() => users.id, { onDelete: "set null" }),
  },
  (t) => [
    unique("role_bindings_unique").on(t.userId, t.roleId, t.scopeType, t.scopeId).nullsNotDistinct(),
    enumCheck("role_bindings_scope_type_check", t.scopeType, ScopeType.options),
    check("role_bindings_scope_id_check", sql`(${t.scopeType} = 'global') = (${t.scopeId} IS NULL)`),
    index("role_bindings_user_idx").on(t.userId),
    index("role_bindings_scope_idx").on(t.scopeType, t.scopeId),
  ],
);

export const apiTokens = pgTable(
  "api_tokens",
  {
    id: uuid("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    tokenHash: text("token_hash").notNull().unique("api_tokens_token_hash_unique"),
    prefix: text("prefix").notNull(),
    scopes: jsonb("scopes").notNull().default([]),
    expiresAt: tsz("expires_at"),
    lastUsedAt: tsz("last_used_at"),
    revokedAt: tsz("revoked_at"),
    createdAt: tsz("created_at").notNull().defaultNow(),
  },
  (t) => [index("api_tokens_user_idx").on(t.userId)],
);

export const setupState = pgTable(
  "setup_state",
  {
    id: integer("id").primaryKey(),
    completedAt: tsz("completed_at"),
    setupTokenHash: text("setup_token_hash"),
    tokenCreatedAt: tsz("token_created_at"),
  },
  (t) => [check("setup_state_singleton", sql`${t.id} = 1`)],
);
