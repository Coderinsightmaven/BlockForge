import { describe, expect, it } from "vitest";
import {
  PropertiesSyntaxError,
  duplicateKeys,
  escapePropertyKey,
  escapePropertyValue,
  getProperties,
  getProperty,
  parseProperties,
  serializeProperties,
  setProperties,
  unescapeProperties,
  updatePropertiesText,
} from "../src/index.js";
import { fixture } from "./helpers.js";

const REAL = ["properties/vanilla-26.3.server.properties", "properties/vanilla-1.21.8.server.properties", "properties/vanilla-1.20.3.server.properties"];

describe("server.properties round-trip (real files generated by the official jars)", () => {
  it.each(REAL)("%s is reproduced byte-for-byte", (f) => {
    const text = fixture(f);
    expect(serializeProperties(parseProperties(text))).toBe(text);
  });

  it("round-trips CRLF and CR line endings and missing trailing newline", () => {
    const crlf = fixture(REAL[0]!).replace(/\n/g, "\r\n");
    expect(serializeProperties(parseProperties(crlf))).toBe(crlf);
    expect(parseProperties(crlf).eol).toBe("\r\n");
    const cr = "a=1\rb=2\r";
    expect(serializeProperties(parseProperties(cr))).toBe(cr);
    const noTrail = "#c\na=1";
    expect(serializeProperties(parseProperties(noTrail))).toBe(noTrail);
  });

  it("decodes values from the real 26.3 file", () => {
    const props = getProperties(parseProperties(fixture(REAL[0]!)));
    expect(props["level-type"]).toBe("minecraft:normal");
    expect(props["motd"]).toBe("A Minecraft Server");
    expect(props["generator-settings"]).toBe("{}");
    expect(props["white-list"]).toBe("true");
    expect(props["pvp"]).toBeUndefined();
    expect(Object.keys(props)).toHaveLength(69);
  });

  it("edits only the targeted lines", () => {
    const text = fixture(REAL[0]!);
    const out = updatePropertiesText(text, { motd: "Hello: world = §aGreen", "max-players": 50, "online-mode": false });
    const before = text.split("\n");
    const after = out.split("\n");
    expect(after).toHaveLength(before.length);
    const changed = before.map((l, i) => (l === after[i] ? null : [l, after[i]])).filter(Boolean);
    expect(changed).toEqual([
      ["max-players=20", "max-players=50"],
      ["motd=A Minecraft Server", "motd=Hello\\: world \\= §aGreen"],
      ["online-mode=true", "online-mode=false"],
    ]);
    expect(getProperty(parseProperties(out), "motd")).toBe("Hello: world = §aGreen");
  });

  it("does not touch entries whose value is unchanged and appends new keys", () => {
    // Java joins continuation lines without a separator: "value" + "continued".
    const text = "#x\nkey = value\\\n    continued\n";
    expect(getProperty(parseProperties(text), "key")).toBe("valuecontinued");
    expect(updatePropertiesText(text, { key: "valuecontinued" })).toBe(text);
    expect(updatePropertiesText(text, { other: "1" })).toBe(`${text}other=1\n`);
    expect(updatePropertiesText("a=1", { b: "2" })).toBe("a=1\nb=2\n");
    expect(updatePropertiesText("a=1\r\n", { b: "2" })).toBe("a=1\r\nb=2\r\n");
  });

  it("keeps indentation, key spelling and separator style when rewriting", () => {
    expect(updatePropertiesText("  key : old\n", { key: "new" })).toBe("  key : new\n");
    expect(updatePropertiesText("key\told\n", { key: "new" })).toBe("key\tnew\n");
    expect(updatePropertiesText("multi = a\\\n  b\nnext=1\n", { multi: "x" })).toBe("multi = x\nnext=1\n");
    expect(updatePropertiesText("k\\\n = v\n", { k: "w" })).toBe("k=w\n");
  });

  it("removes every occurrence with null and reports duplicates (last wins)", () => {
    const doc = parseProperties("a=1\nb=2\na=3\n");
    expect(getProperty(doc, "a")).toBe("3");
    expect(duplicateKeys(doc)).toEqual(["a"]);
    expect(serializeProperties(setProperties(doc, { a: "9" }))).toBe("a=1\nb=2\na=9\n");
    expect(serializeProperties(setProperties(doc, { a: null }))).toBe("b=2\n");
  });
});

describe("escaping (java.util.Properties semantics)", () => {
  it("parses separators, comments and whitespace", () => {
    const doc = parseProperties(["# comment", "! bang comment", "   ", "a=1", "b:2", "c 3", "d   =   4", "e", "\t f=6", "g=  7"].join("\n"));
    expect(getProperties(doc)).toEqual({ a: "1", b: "2", c: "3", d: "4", e: "", f: "6", g: "7" });
    expect(doc.lines.filter((l) => l.kind === "comment")).toHaveLength(2);
  });

  it("handles escapes in keys and values", () => {
    const doc = parseProperties(
      [
        "key\\ with\\ spaces=v",
        "colon\\:key=a\\=b",
        "uni=\\u00e9t\\u00E9",
        "tabs=a\\tb\\nc",
        "other=\\q\\#\\!",
        "lead=\\  two leading",
        "trail=x\\\\",
      ].join("\n"),
    );
    expect(getProperties(doc)).toEqual({
      "key with spaces": "v",
      "colon:key": "a=b",
      uni: "été",
      tabs: "a\tb\nc",
      other: "q#!",
      lead: "  two leading",
      trail: "x\\",
    });
  });

  it("joins continuation lines and drops their leading whitespace", () => {
    const doc = parseProperties("fruits = apple, \\\n          banana, \\\n\t\tpear\nafter=1\n# comment ending in \\\nz=2");
    expect(getProperty(doc, "fruits")).toBe("apple, banana, pear");
    expect(getProperty(doc, "after")).toBe("1");
    expect(getProperty(doc, "z")).toBe("2");
    expect(getProperty(parseProperties("even=a\\\\\nnext=1"), "even")).toBe("a\\");
  });

  it("rejects malformed \\u escapes", () => {
    expect(() => parseProperties("a=\\u12G4")).toThrow(PropertiesSyntaxError);
    expect(() => unescapeProperties("\\u12")).toThrow(/Malformed/);
  });

  it("escapes like Properties.store", () => {
    expect(escapePropertyKey("a b:c=d#e!f")).toBe("a\\ b\\:c\\=d\\#e\\!f");
    expect(escapePropertyValue(" lead inner ")).toBe("\\ lead inner ");
    expect(escapePropertyValue("minecraft:normal")).toBe("minecraft\\:normal");
    expect(escapePropertyValue("a\\b\tc\nd")).toBe("a\\\\b\\tc\\nd");
    expect(escapePropertyValue("ctl\u0001\u007f")).toBe("ctl\\u0001\\u007F");
    expect(escapePropertyValue("é§")).toBe("é§");
    expect(escapePropertyValue("é§", { asciiOnly: true })).toBe("\\u00E9\\u00A7");
  });

  it("round-trips arbitrary values through set → parse", () => {
    const tricky = [" leading", "trailing ", "a=b:c", "#hash", "!bang", "back\\slash", "tab\tnew\nline\r", "üñí§ode", "", "\u0000x"];
    let doc = parseProperties("");
    tricky.forEach((v, i) => (doc = setProperties(doc, { [`k${i} x`]: v })));
    const reparsed = getProperties(parseProperties(serializeProperties(doc)));
    tricky.forEach((v, i) => expect(reparsed[`k${i} x`]).toBe(v));
  });
});
